// Rebuild the bundled PCM from the small, locally cached MP3 files.
// No network requests: place downloads and their source JSON in artifacts/meme-import/.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import ffmpeg from 'ffmpeg-static';
import {MEME_SOUNDS} from '../src/meme-catalog.js';

const ids=Object.keys(MEME_SOUNDS);
const clips={},sources=[];
for(const id of ids){
  const path=`artifacts/meme-import/${id}`,input=await readFile(path+'.mp3');
  const result=spawnSync(ffmpeg,['-v','error','-i',path+'.mp3','-t','5','-ac','1','-ar','24000','-f','f32le','pipe:1'],{windowsHide:true});
  if(result.status!==0)throw Error(`${id}: ${result.stderr}`);
  const samples=Array.from({length:result.stdout.length/4},(_,i)=>result.stdout.readFloatLE(i*4));
  const peak=samples.reduce((p,s)=>Math.max(p,Math.abs(s)),0);
  if(!peak)throw Error(`${id}: silent clip`);
  const threshold=peak*.008;
  const start=Math.max(0,samples.findIndex(s=>Math.abs(s)>threshold)-240);
  const end=Math.min(samples.length,samples.findLastIndex(s=>Math.abs(s)>threshold)+481);
  const pcm=Buffer.alloc((end-start)*2);
  for(let i=start;i<end;i++){
    const envelope=Math.min(1,(i-start)/48,(end-1-i)/360);
    pcm.writeInt16LE(Math.round(samples[i]/peak*.7*envelope*32767),(i-start)*2);
  }
  clips[id]={rate:24000,pcm:pcm.toString('base64')};
  sources.push({...JSON.parse(await readFile(path+'.json','utf8')),sha256:createHash('sha256').update(input).digest('hex'),trimStart:start/24000,duration:(end-start)/24000});
}
await mkdir('public/audio/memes',{recursive:true});
await writeFile('src/meme-audio-data.js','// Generated by scripts/import-meme-sounds.mjs; mono PCM16, little endian.\nexport const PCM_CLIPS='+JSON.stringify(clips)+';\n');
await writeFile('public/audio/memes/sources.json',JSON.stringify({version:1,format:'PCM16 mono 24000 Hz; bundled in src/meme-audio-data.js',note:'Soundboard variants, not extractions from the researched YouTube videos. Source pages do not establish a redistribution license.',sources},null,2)+'\n');
console.log(sources.map(s=>`${s.id}: ${s.duration.toFixed(3)} s`).join('\n'));
