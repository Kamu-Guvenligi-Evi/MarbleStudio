import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:5173?edit=1');
  await page.waitForFunction(()=>window.marbleStudio);
  const state=()=>page.evaluate(()=>window.marbleStudio.getState());
  assert.equal(await page.locator('.view-tabs button').count(),4);
  assert.equal(await page.locator('#build-view, #library-dialog, #section-dialog, #projects-dialog').count(),0);
  assert.equal((await state()).workspace,'track');
  assert.equal(await page.locator('#track-view #race').isVisible(),true);
  await page.locator('#track-preset').selectOption('pinball');
  const sections=(await state()).sections;
  await page.locator('#count').selectOption('8');
  await page.locator('#music-title').click();
  await page.locator('#music-volume').fill('20');
  await page.locator('#open-balls').click();
  await page.locator('[data-name="0"]').fill('Track Racer');
  await page.locator('[data-name="0"]').press('Tab');
  await page.locator('[data-close="balls-dialog"]').click();
  await page.screenshot({path:'artifacts/studio-track-desktop.png',fullPage:true});
  await page.locator('#nav-arena').click();
  assert.equal((await state()).workspace,'arena');
  assert.equal((await state()).count,12);
  assert.notEqual((await state()).names[0],'Track Racer');
  assert.equal(await page.locator('#arena-view #race').isVisible(),true);
  assert.equal(await page.locator('#track-view').isVisible(),false);
  assert.equal(await page.locator('#track-preset').isVisible(),false);
  assert.equal(await page.locator('#music-mode').inputValue(),'fixed');
  assert.equal(await page.locator('#music-volume').inputValue(),'35');
  await page.locator('#count').selectOption('6');
  await page.locator('#music-volume').fill('65');
  await page.screenshot({path:'artifacts/studio-arena-desktop.png',fullPage:true});
  await page.locator('#nav-track').click();
  assert.equal((await state()).count,8);
  assert.equal((await state()).names[0],'Track Racer');
  assert.deepEqual((await state()).sections,sections);
  assert.equal(await page.locator('#music-volume').inputValue(),'20');
  await page.locator('#pause').click();
  await page.waitForFunction(()=>window.marbleStudio.getState().countdown>0||window.marbleStudio.getState().state==='running');
  await page.locator('#nav-statistics').click();
  assert.equal((await state()).paused,true);
  assert.equal(await page.locator('#statistics-view').isVisible(),true);
  assert.equal(await page.locator('#watch-view').isVisible(),false);
  assert.equal(await page.locator('#open-settings').isVisible(),false);
  await page.screenshot({path:'artifacts/studio-statistics-desktop.png',fullPage:true});
  await page.locator('#nav-arena').click();
  assert.equal((await state()).count,6);
  assert.equal(await page.locator('#music-volume').inputValue(),'65');
  await page.reload();await page.waitForFunction(()=>window.marbleStudio);
  assert.equal((await state()).count,8);
  await page.locator('#nav-arena').click();assert.equal((await state()).count,6);
  await page.locator('#webm-options').evaluate(el=>el.open=true);await page.locator('#record').click();
  await page.waitForFunction(()=>window.marbleStudio.getState().recording);
  await page.waitForFunction(()=>window.marbleStudio.getState().time>.2);
  for(const id of ['nav-track','nav-statistics','count','open-balls','open-settings'])assert.equal(await page.locator('#'+id).isDisabled(),true,id);
  const download=page.waitForEvent('download');
  await page.locator('#webm-options').evaluate(el=>el.open=true);await page.locator('#record').click();await download;
  await page.waitForFunction(()=>!document.querySelector('#nav-track').disabled);
  await page.setViewportSize({width:390,height:844});
  for(const mode of ['track','arena','statistics','spiral']){
    await page.locator('#nav-'+mode).click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,mode+' mobile overflow');
    await page.screenshot({path:'artifacts/studio-'+mode+'-mobile.png',fullPage:true});
  }
  assert.deepEqual(errors,[]);
  console.log('PASS: four workspaces, editor removal, isolated rosters/settings/music, persistence, playback, recording locks/download, mobile layouts.');
}finally{await browser.close();}
