// Rebuild from the locally cached Mackolik notification; no network requests.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import ffmpeg from 'ffmpeg-static';

const input='artifacts/mackolik-official-goal.mp3',rate=24000;
const original=await readFile(input);
const result=spawnSync(ffmpeg,['-v','error','-i',input,'-ac','1','-ar',String(rate),'-f','f32le','pipe:1'],{windowsHide:true});
if(result.status!==0)throw Error(result.stderr.toString());
const floats=result.stdout,count=floats.length/4;
const duration=count/rate;
if(duration<2.9||duration>3.1)throw Error('Unexpected official goal notification duration');
let peak=0;
for(let i=0;i<count;i++)peak=Math.max(peak,Math.abs(floats.readFloatLE(i*4)));
if(peak<.01)throw Error('Silent goal recording');
const pcm=Buffer.alloc(count*2);
for(let i=0;i<count;i++){
  const fade=Math.min(1,i/(rate*.003),(count-1-i)/(rate*.01));
  pcm.writeInt16LE(Math.round(floats.readFloatLE(i*4)/peak*.95*fade*32767),i*2);
}
await writeFile('src/goal-arena-audio-data.js','// Generated by scripts/import-goal-crowd.mjs. Mackolik notification sample; see public/audio/goal-arena/source.json.\nexport const GOAL_CROWD='+JSON.stringify({rate,duration,pcm:pcm.toString('base64')})+';\n');
await mkdir('public/audio/goal-arena',{recursive:true});
await writeFile('public/audio/goal-arena/source.json',JSON.stringify({
  title:'Mackolik goal sound',
  source:'https://arsiv.mackolik.com/Canli-Sonuclar',
  download:'https://im.mackolik.com/img5/goal_sound.mp3',
  license:'No reuse license stated by the source',
  copyright:'Rights remain with their respective holders.',
  description:'Goal audio from the official Mackolik live scores page. Its goal_sound_player element loads this MP3, and Mackolik.LiveScore.playSound plays that element.',
  sourceSha256:createHash('sha256').update(original).digest('hex'),
  trimStart:0,duration,rate,processing:'Complete clip at original speed; mono PCM16; peak normalized to 0.95; 3 ms attack and 10 ms release.',
},null,2)+'\n');
console.log(`Bundled Mackolik goal notification: ${duration}s, ${rate}Hz, ${pcm.length} PCM bytes.`);
