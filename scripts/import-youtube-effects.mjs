import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
import ffmpeg from 'ffmpeg-static';

const folder=process.argv[2]??'artifacts/youtube-effects',rate=24000;
const clips=[
  {id:'cash-register',name:'Kasa · Cha-Ching',video:'EuLJv2qONRY',start:2.85,end:4.55},
  {id:'minecraft-villager',name:'Minecraft köylüsü',video:'fiwRZ_j61Dc',start:2.10,end:2.67},
];
await mkdir('public/audio/youtube',{recursive:true});
const recorded={},manifest=[];
for(const clip of clips){
  const duration=clip.end-clip.start,source=path.join(folder,clip.video+'.webm');
  const metadata=JSON.parse(await readFile(path.join(folder,clip.video+'.info.json'),'utf8'));
  const result=spawnSync(ffmpeg,['-hide_banner','-loglevel','error','-ss',String(clip.start),'-i',source,'-t',String(duration),'-vn','-ac','1','-ar',String(rate),'-af',`afade=t=in:d=0.005,afade=t=out:st=${duration-.025}:d=0.025`,'-f','f32le','pipe:1'],{windowsHide:true,maxBuffer:4*1024*1024});
  if(result.status!==0)throw new Error(result.stderr.toString());
  const input=result.stdout,count=input.length/4;
  let peak=0;for(let i=0;i<count;i++)peak=Math.max(peak,Math.abs(input.readFloatLE(i*4)));
  if(peak<.001)throw new Error('Empty effect: '+clip.id);
  const pcm=Buffer.alloc(count*2),gain=.6/peak;
  for(let i=0;i<count;i++)pcm.writeInt16LE(Math.round(input.readFloatLE(i*4)*gain*32767),i*2);
  const wave=Buffer.alloc(44+pcm.length);wave.write('RIFF');wave.writeUInt32LE(36+pcm.length,4);wave.write('WAVEfmt ',8);
  wave.writeUInt32LE(16,16);wave.writeUInt16LE(1,20);wave.writeUInt16LE(1,22);wave.writeUInt32LE(rate,24);wave.writeUInt32LE(rate*2,28);wave.writeUInt16LE(2,32);wave.writeUInt16LE(16,34);wave.write('data',36);wave.writeUInt32LE(pcm.length,40);pcm.copy(wave,44);
  const file='/audio/youtube/'+clip.id+'.wav';await writeFile('public'+file,wave);
  const details={...clip,source:'https://www.youtube.com/watch?v='+clip.video,sourceTitle:metadata.title,creator:metadata.uploader,rate,duration:count/rate,file};
  manifest.push(details);recorded[clip.id]={name:clip.name,rate,duration:count/rate,pcm:pcm.toString('base64')};
  console.log(`${clip.id}: ${(count/rate).toFixed(2)} seconds, normalized peak 0.6.`);
}
await writeFile('public/audio/youtube/source.json',JSON.stringify({method:'User-selected single effects; edge silence trimmed, 5/25 ms fades, mono PCM at 24 kHz, peak normalized to 0.6.',clips:manifest},null,2)+'\n');
await writeFile('src/recorded-sound-data.js','// Generated by scripts/import-youtube-effects.mjs. PCM is shared by live and offline playback.\nexport const RECORDED_SOUNDS='+JSON.stringify(recorded)+';\n');
